    /// Cumulative day offset of the start of each month, and the exclusive JDN support end.
    private static let table: (months: [Int], jdSupportEnd: Int) = {
        var months = [Int](repeating: 0, count: hijriMonths.count * 12)
        var jd = 0
        for m in 0..<(hijriMonths.count * 12) {
            months[m] = jd
            jd += ((Int(hijriMonths[m / 12]) >> (11 - m % 12)) & 1) == 1 ? 30 : 29
        }
        return (months, jd + supportedStartJdn)
    }()

    private static var months: [Int] { table.months }
    private static var jdSupportEnd: Int { table.jdSupportEnd }
    private static var supportedYears: Int { hijriMonths.count }

    /// Returns -1 when the year is outside the supported range.
    static func toJdn(_ year: Int, _ month: Int, _ day: Int) -> Int {
        let yearIndex = year - supportedStartYear
        guard (0..<supportedYears).contains(yearIndex) else { return -1 }
        return months[yearIndex * 12 + month - 1] + day + supportedStartJdn - 1
    }

    static func fromJdn(_ jd: Int) -> DateTriplet? {
        guard jd >= supportedStartJdn && jd < jdSupportEnd else { return nil }
        let days = jd - supportedStartJdn
        let months = self.months
        var index = days / 30
        while index + 1 < months.count && months[index + 1] <= days { index += 1 }
        let yearIndex = index / 12
        let month = index % 12
        let day = days - months[index]
        return DateTriplet(
            year: yearIndex + supportedStartYear,
            month: month + 1,
            dayOfMonth: day + 1
        )
    }
